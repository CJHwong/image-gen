"""Exercise installed CPU example plugins through UI and API, without --stub.

Start: uv run --with ./examples/model_plugin studio --config examples/model_plugin/studio.toml --port <port>
"""

import io
import sys
import time

from PIL import Image
from playwright.sync_api import expect, sync_playwright

URL = "http://127.0.0.1:" + sys.argv[1]

with sync_playwright() as tool:
    browser = tool.chromium.launch()
    context = browser.new_context(viewport={"width": 1440, "height": 1000})
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(URL, wait_until="domcontentloaded")
    page.wait_for_function("typeof busy === 'function'")
    expect(page.locator("#backend-toggle .name")).to_have_text("Example Image")
    expect(page.locator("#rewrite-toggle")).to_be_hidden()
    page.locator("#prompt").fill("A plugin PNG generated by the UI")
    page.locator("#go").click()
    page.wait_for_function("gallery.length === 1 && !busy()", timeout=30000)
    image = page.evaluate("async () => Array.from(new Uint8Array(await (await fetch(gallery[0].src)).arrayBuffer()))")
    with Image.open(io.BytesIO(bytes(image))) as png:
        assert png.size == (256, 256)
    print("PASS external Image plugin produces valid PNG through UI", flush=True)

    page.locator("#media-video-mode").click()
    expect(page.locator("#backend-toggle .name")).to_have_text("Example Video")
    expect(page.locator("#video-rewrite-toggle")).to_be_hidden()
    page.locator("#video-prompt").fill("A CPU plugin test clip")
    page.locator("#video-generate").click()
    page.wait_for_function(
        "videoStudio.clips.some(clip=>clip.kind==='generated' && !clip.stub) && !videoStudio.generationProgress",
        timeout=30000,
    )
    expect(page.locator("#video-preview")).to_be_visible()
    page.wait_for_function("document.querySelector('#video-preview').videoWidth === 256")
    print("PASS external Video plugin produces playable MP4; unrelated Rewrite stays hidden", flush=True)

    page.locator("#media-voice-mode").click()
    expect(page.locator("#backend-toggle .name")).to_have_text("Example Voice")
    page.wait_for_function("document.querySelector('#voice-studio').ready")
    page.locator("#voice-text").fill("A demonstration tone, not synthesized speech.")
    page.locator("#voice-generate").click()
    page.wait_for_function(
        "document.querySelector('#voice-studio').takesCount===1 && !document.querySelector('#voice-studio').locked",
        timeout=30000,
    )
    page.wait_for_function("document.querySelector('#voice-studio').previewReady")
    print("PASS external Voice plugin produces playable WAV through UI", flush=True)

    for kind, backend in [("image", "example_image"), ("video", "example_video"), ("voice", "example_voice")]:
        items = (
            [{"text": "First demo tone"}, {"text": "Second demo tone"}]
            if kind == "voice"
            else [{"prompt": "First plugin result", "seed": 11}, {"prompt": "Second plugin result", "seed": 12}]
        )
        if kind == "video":
            items = [dict(item, width=256, height=256, num_frames=17, frame_rate=8) for item in items]
        response = context.request.post(
            URL + "/api/v1/operations", data={"kind": kind, "backend": backend, "items": items}
        )
        assert response.status == 202, response.text()
        operation = response.json()
        deadline = time.monotonic() + 30
        while True:
            state = context.request.get(URL + operation["status_url"]).json()
            if state["status"] in ("succeeded", "failed", "cancelled"):
                break
            assert time.monotonic() < deadline, state
            time.sleep(0.1)
        assert state["status"] == "succeeded", state
        result = context.request.get(URL + state["result_url"])
        assert result.ok, result.text()
        print("PASS two-item " + kind + " batch through the existing operation API", flush=True)

    invalid = context.request.post(
        URL + "/api/v1/operations",
        data={
            "kind": "video",
            "backend": "example_video",
            "prompt": "Bad size",
            "width": 1024,
            "height": 1024,
            "num_frames": 17,
            "frame_rate": 8,
        },
    )
    assert invalid.status == 202, invalid.text()
    deadline = time.monotonic() + 30
    while True:
        state = context.request.get(URL + invalid.json()["status_url"]).json()
        if state["status"] in ("succeeded", "failed"):
            break
        assert time.monotonic() < deadline, state
        time.sleep(0.1)
    assert state["status"] == "failed", state
    assert "256" in state["error"], state
    assert not errors, errors
    print("PASS plugin capability limits are enforced; no page errors", flush=True)
    browser.close()
